const {
  generateReportsFromRaw,
} = require('./report-utils');

module.exports = async function reportGlobalTeardown() {
  try {
    const outputs = await generateReportsFromRaw();
    console.log(`\nExecution PDF report generated by teardown: ${outputs.pdfPath}`);
    console.log(`Test case Excel workbook generated by teardown: ${outputs.excelPath}`);
  } catch (error) {
    console.error('\nReport teardown fallback could not generate reports.');
    console.error(error && error.stack ? error.stack : error);
  }
};
